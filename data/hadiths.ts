// دالة لجلب حديث اليوم حسب اليوم من السنة (ثابت لكل يوم)
export function getTodayHadith(): DailyHadith {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = dayOfYear % DAILY_HADITHS.length;
  return DAILY_HADITHS[index] || DAILY_HADITHS[0];
}

// دالة لجلب حديث عشوائي عند الضغط على "حديث آخر"
export function getRandomHadith(excludeId?: number): DailyHadith {
  const candidates = DAILY_HADITHS.filter(h => h.id !== excludeId);
  const randomIndex = Math.floor(Math.random() * candidates.length);
  return candidates[randomIndex] || DAILY_HADITHS[0];
}
